CREATE TABLE IF NOT EXISTS design_files (
 path TEXT PRIMARY KEY, base_content TEXT NOT NULL, content TEXT NOT NULL,
 revision INTEGER NOT NULL DEFAULT 0, enabled BOOLEAN NOT NULL DEFAULT FALSE,
 conflict BOOLEAN NOT NULL DEFAULT FALSE, updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS design_revisions (
 id TEXT PRIMARY KEY, path TEXT NOT NULL REFERENCES design_files(path),
 revision INTEGER NOT NULL, content TEXT NOT NULL, user_id TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(path,revision)
);
