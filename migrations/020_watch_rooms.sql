CREATE TABLE IF NOT EXISTS watch_room_limits(id INTEGER PRIMARY KEY);
INSERT INTO watch_room_limits(id) VALUES(1) ON CONFLICT(id) DO NOTHING;
CREATE TABLE IF NOT EXISTS watch_rooms(
 id TEXT PRIMARY KEY, owner_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 anime_id TEXT NOT NULL REFERENCES anime(id) ON DELETE CASCADE, release_id INTEGER NOT NULL,
 episode INTEGER NOT NULL, position REAL NOT NULL DEFAULT 0, playing BOOLEAN NOT NULL DEFAULT FALSE,
 version INTEGER NOT NULL DEFAULT 0, updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), expires_at TIMESTAMPTZ NOT NULL, closed_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS watch_room_members(
 room_id TEXT NOT NULL REFERENCES watch_rooms(id) ON DELETE CASCADE,
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 active BOOLEAN NOT NULL DEFAULT TRUE, kicked BOOLEAN NOT NULL DEFAULT FALSE,
 last_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(), PRIMARY KEY(room_id,user_id)
);
CREATE TABLE IF NOT EXISTS watch_room_messages(
 seq BIGSERIAL PRIMARY KEY, request_id TEXT NOT NULL UNIQUE,
 room_id TEXT NOT NULL REFERENCES watch_rooms(id) ON DELETE CASCADE,
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 body TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS room_messages_cursor ON watch_room_messages(room_id,seq);
CREATE INDEX IF NOT EXISTS room_expiry ON watch_rooms(expires_at);
