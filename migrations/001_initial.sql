CREATE TABLE IF NOT EXISTS anime (
 id TEXT PRIMARY KEY, shikimori_id INTEGER UNIQUE, name TEXT NOT NULL,
 original_name TEXT NOT NULL DEFAULT '', year INTEGER, country TEXT NOT NULL DEFAULT 'Япония',
 kind TEXT NOT NULL DEFAULT 'tv', status TEXT NOT NULL DEFAULT 'anons',
 rating REAL NOT NULL DEFAULT 0, episodes INTEGER NOT NULL DEFAULT 0,
 aired INTEGER NOT NULL DEFAULT 0, genres TEXT[] NOT NULL DEFAULT '{}',
 description TEXT NOT NULL DEFAULT '', poster TEXT NOT NULL DEFAULT '',
 metadata JSONB NOT NULL DEFAULT '{}', protected_fields TEXT[] NOT NULL DEFAULT '{}',
 blocked BOOLEAN NOT NULL DEFAULT FALSE, block_reason TEXT NOT NULL DEFAULT '',
 views INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), synced_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS anime_updates ON anime(updated_at);
CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, email TEXT UNIQUE, name TEXT NOT NULL, password_hash TEXT,
 telegram_id TEXT UNIQUE, role TEXT NOT NULL DEFAULT 'user', verified BOOLEAN NOT NULL DEFAULT FALSE,
 avatar TEXT NOT NULL DEFAULT '', cover TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 csrf TEXT NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS email_tokens (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 purpose TEXT NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS library (
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 anime_id TEXT NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
 status TEXT NOT NULL DEFAULT 'planned', score INTEGER,
 PRIMARY KEY(user_id,anime_id)
);
CREATE TABLE IF NOT EXISTS watch_history (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 anime_id TEXT NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
 episode INTEGER NOT NULL, position_seconds INTEGER NOT NULL DEFAULT 0,
 completed BOOLEAN NOT NULL DEFAULT FALSE, updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT watch_history_user_id_anime_id_episode_key UNIQUE(user_id,anime_id,episode)
);
CREATE TABLE IF NOT EXISTS comments (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), anime_id TEXT NOT NULL REFERENCES anime(id),
 body TEXT NOT NULL, spoiler BOOLEAN NOT NULL DEFAULT FALSE, hidden BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS jobs (
 id TEXT PRIMARY KEY, kind TEXT NOT NULL, payload JSONB NOT NULL DEFAULT '{}',
 status TEXT NOT NULL DEFAULT 'pending', attempts INTEGER NOT NULL DEFAULT 0,
 run_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), locked_at TIMESTAMPTZ, error TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS audit (
 id TEXT PRIMARY KEY, user_id TEXT REFERENCES users(id), action TEXT NOT NULL,
 entity_id TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS media (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), mime TEXT NOT NULL,
 bytes BYTEA NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
